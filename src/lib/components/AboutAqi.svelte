	<h2 id="about-title">Tentang AQI</h2>
	<div class="body">
		<p>
			Angka utama di halaman ini adalah <strong>Universal AQI</strong> dari Google. Indeks ini dihitung dari
			kadar beberapa polutan dan memakai skala 0–100: semakin tinggi angkanya, semakin baik kualitas udaranya.
			Nama kategori dan rekomendasi kesehatan berasal langsung dari Google.
		</p>
		<p>
			Universal AQI berbeda dengan ISPU, indeks resmi pemerintah Indonesia, yang justru makin buruk saat
			angkanya makin tinggi. Jangan membandingkan kedua angka secara langsung.
		</p>
		<p>
			Data merupakan perkiraan per jam, bukan hasil satu alat ukur di titik tersebut. Pilihan kota memakai
			satu titik referensi di pusat kota, sehingga kondisi di bagian lain kota bisa berbeda. Gunakan sebagai
			gambaran umum, bukan nasihat medis.
		</p>
